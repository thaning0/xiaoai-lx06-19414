"""Import reused compiled release components, never boot/updater or firmware code.

Only the exact pinned local inputs are accepted. Provenance is a sibling JSON,
not part of the overlay. Source compilation via packages.sh remains supported.
"""
import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import tarfile
import tempfile

try:
    from . import lx06_offline_build as build
    from . import lx06_profile as profile
except ImportError:
    import lx06_offline_build as build
    import lx06_profile as profile

BASE = {'size': 36703430, 'sha256': '378d6d654a8138f36588f682d3da3a67dca956f2fc863b01c588ef4d3759cd41',
        'url': 'https://cdn.cnbj1.fds.api.mi-img.com/xiaoqiang/rom/lx06/mico_firmware_9c712_1.74.10.bin',
        'container_sha256': 'bd88b2611495acb8bfab658150c8a99b515551d6a0851a2d9725c798640633b3',
        'container_size': 41954280}
RELEASE = {'size': 40673280, 'sha256': '0e4edc5de66118ff23f6bcf321851421468c2e1fad62a9df697495608c2584de',
           'url': 'https://github.com/duhow/xiaoai-patch/releases/download/2026.3.26/mico_firmware_080b2a0_260329_lx06.tar'}
EXACT = {'etc/passwd', 'etc/group', 'etc/shadow', 'etc/os-release', 'etc/crontabs',
         'root/.ssh', 'etc/init.d/dlnainit', 'etc/init.d/mdplay', 'etc/init.d/mitv-disc',
         'etc/init.d/alsa', 'etc/rc.d/S51hostname', 'etc/profile.d/python-site-packages-bin.sh',
         'usr/sbin/boot_function.sh'}


def excluded(name):
    targets = json.loads((profile.PROFILE/'manifest.json').read_text())['targets']
    if name in targets:
        return 'exact 1.94.14 profile target'
    if build.protected(name):
        return 'original hardware/calibration'
    if name in EXACT or any(name.startswith(p+'/') for p in EXACT):
        return 'stock or generated by default scripts'
    if name.startswith(('usr/share/sound', 'usr/share/common_sound', 'usr/share/mico/', 'mico/')):
        return 'firmware metadata or sound content'
    if name.startswith('bin/') and ((build.REPO/name).exists() or (build.REPO/name).is_symlink()):
        return 'repository bin script'
    return None


def pinned(value, expected):
    path = build.safe_path(value)
    if not path.is_file() or path.stat().st_size != expected['size'] or profile.digest(path) != expected['sha256']:
        raise ValueError('input size/SHA256 mismatch: '+str(path))
    return path


def extract(image, destination):
    # umask 0 prevents a non-root extraction dropping original group-write bits.
    subprocess.run(['/usr/bin/unsquashfs', '-no-progress', '-strict-errors', '-excludes',
                    '-d', str(destination), str(image), 'dev/console'], check=True, umask=0,
                   stdout=subprocess.DEVNULL)


def import_overlay(original, release, output):
    original = pinned(original, BASE)
    release = pinned(release, RELEASE)
    output = build.safe_path(output)
    provenance = output.with_name(output.name+'.source.json')
    if output.exists() or provenance.exists() or not output.parent.is_dir():
        raise ValueError('overlay and sibling provenance must be new')
    with tempfile.TemporaryDirectory(prefix='.lx06-import-', dir=output.parent) as tmp:
        work = Path(tmp)
        # Inspect every member, but read ONLY the rootfs. Never extract boot/updater.
        with tarfile.open(release, 'r:') as archive:
            members = archive.getmembers()
            expected = {'.', './update.sh', './root.squashfs', './boot.img', './metadata'}
            if len(members) != 5 or {m.name for m in members} != expected:
                raise ValueError('unexpected release TAR shape')
            if any(not (m.isdir() if m.name == '.' else m.isfile()) for m in members):
                raise ValueError('unexpected release TAR member type')
            with archive.extractfile('./root.squashfs') as source, (work/'release.squashfs').open('xb') as dest:
                shutil.copyfileobj(source, dest)
        extract(original, work/'stock')
        extract(work/'release.squashfs', work/'release')
        old = build.inventory(work/'stock'); new = build.inventory(work/'release')
        included = {}; exclusions = {}; stage = work/'overlay'; stage.mkdir()
        for name, entry in new.items():
            if entry['type'] == 'directory' or old.get(name) == entry:
                continue
            reason = excluded(name)
            if entry['type'] == 'file':
                with (work/'release'/name).open('rb') as stream:
                    header = stream.read(20)
                if header[:4] == b'\x7fELF' and (header[4:6] != b'\x01\x01' or header[18:20] != b'\x28\x00'):
                    reason = 'non-ARM userspace release artifact (host Python extension)'
            if reason:
                exclusions[name] = reason
                continue
            source = work/'release'/name; dest = stage/name
            # Parents must be real directories in the source and staged overlay.
            for parent in source.parents:
                if parent == work/'release':
                    break
                if parent.is_symlink():
                    raise ValueError('symlink ancestor: '+name)
            dest.parent.mkdir(parents=True, exist_ok=True)
            if entry['type'] == 'symlink':
                dest.symlink_to(entry['target'])
            else:
                shutil.copy2(source, dest)
            included[name] = entry
        build.overlay_check(stage)
        report = {'status': 'imported-offline-hardware-unverified', 'release': '2026.3.26',
                  'method': 'Changed/new leaves versus exact original 1.74.10; no deletion propagation. Reused compiled upstream release components, NOT freshly compiled or a formal packages.sh artifact.',
                  'original_squashfs': BASE, 'release_tar': RELEASE,
                  'release_rootfs_sha256': profile.digest(work/'release.squashfs'),
                  'release_gtag': 'fb070495955668f825700bbd988d5443e9bcadb3',
                  'importer_sha256': profile.digest(Path(__file__)),
                  'included': included, 'excluded': exclusions,
                  'overlay_inventory': build.inventory(stage)}
        stage.rename(output)
        provenance.write_text(json.dumps(report, indent=2)+'\n')
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--original-squashfs', required=True)
    parser.add_argument('--release-tar', required=True)
    parser.add_argument('--output', required=True)
    args = parser.parse_args()
    report = import_overlay(args.original_squashfs, args.release_tar, args.output)
    print(json.dumps({'included': len(report['included']), 'excluded': len(report['excluded'])}))


if __name__ == '__main__':
    main()
